// Bundles the pure-TypeScript rules engine (src/engine) into one ESM file for the
// Supabase Edge Function `game-action` (Deno can't resolve the engine's
// extensionless imports, and deploys only include the function's own files).
//
//   npm run build:edge   ->  supabase/functions/_shared/engine.js
//
// The bundle's types come from the hand-maintained _shared/engine.d.ts (the
// subset of the engine API the function uses), linked via @ts-self-types.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'vite'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = resolve(root, 'supabase/functions/_shared')
const outFile = resolve(outDir, 'engine.js')

await build({
  root,
  configFile: false,
  publicDir: false,
  logLevel: 'warn',
  build: {
    lib: {
      entry: resolve(root, 'src/engine/index.ts'),
      formats: ['es'],
      fileName: () => 'engine.js',
    },
    outDir,
    emptyOutDir: false,
    copyPublicDir: false,
    target: 'es2022',
    minify: true,
    sourcemap: false,
    reportCompressedSize: false,
    // (vite keeps line breaks in ES lib builds: names are mangled, lines stay short,
    // which keeps the bundle reviewable and safe to paste into MCP deploys)
  },
})

const header =
  '// @ts-self-types="./engine.d.ts"\n' +
  '// GENERATED by `npm run build:edge` from src/engine (do not edit by hand).\n' +
  '/* oxlint-disable */\n'
writeFileSync(outFile, header + readFileSync(outFile, 'utf8'))
console.log(`wrote ${outFile} (${(readFileSync(outFile).length / 1024).toFixed(1)} KB)`)
